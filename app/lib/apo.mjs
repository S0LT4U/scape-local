// Equalizer APO config handling for the PC-side Boost. Pure functions (no I/O) so they
// can be unit-tested; the Electron main process does the file and registry access.
//
// How it works: we write our own file `scape-local-boost.txt` (scoped to the Scape's
// playback device(s) with a `Device:` line, then `Preamp: +X dB`), and add one managed
// `Include:` block at the end of config.txt. Turning Boost off removes exactly that block
// and deletes the file. Nothing else in config.txt (or Peace's files) is touched.

export const BOOST_FILE = 'scape-local-boost.txt';
export const BLOCK_START = '# >>> Scape Local boost (managed by Scape Local, do not edit)';
export const BLOCK_END = '# <<< Scape Local boost';

/** dB -> linear amplitude percentage (what volume-amplifier extensions show). */
export const dbToPercent = (db) => Math.round(Math.pow(10, db / 20) * 100);

/** Boost levels offered in the UI. `headset: false` = PC (APO) only. */
export const LEVELS = [
  { db: 3, headset: true },
  { db: 6, headset: true },
  { db: 9, headset: true },
  { db: 12, headset: true },
  { db: 14, headset: false },
].map((l) => ({ ...l, percent: dbToPercent(l.db) }));

const eolOf = (text) => (text.includes('\r\n') ? '\r\n' : '\n');

/**
 * APO device selector text for one endpoint, in the same "connection name, device name, {GUID}"
 * form that APO's Editor puts on the clipboard ("Copy device command").
 */
export function deviceSelector(ep) {
  return [ep.iface, ep.name, `{${ep.guid.replace(/[{}]/g, '').toLowerCase()}}`].filter(Boolean).join(' ');
}

export function buildBoostFile(db, endpoints, eol = '\r\n') {
  if (!(db > 0 && db <= 14)) throw new Error('Boost level must be between 0 and +14 dB');
  if (!endpoints.length) throw new Error('No Scape playback device found');
  return [
    `# Scape Local boost: +${db} dB (${dbToPercent(db)}%). Generated by Scape Local; removed when Boost is turned off.`,
    `Device: ${endpoints.map(deviceSelector).join('; ')}`,
    'Channel: all',
    `Preamp: ${db} dB`,
    '',
  ].join(eol);
}

export function hasBlock(configText) {
  return configText.includes(BLOCK_START);
}

/** Append our managed Include block (idempotent). */
export function addBlock(configText) {
  if (hasBlock(configText)) return configText;
  const eol = eolOf(configText || '\r\n');
  const sep = configText.length && !configText.endsWith('\n') ? eol : '';
  return `${configText}${sep}${BLOCK_START}${eol}Include: ${BOOST_FILE}${eol}${BLOCK_END}${eol}`;
}

/**
 * Remove our managed block. If `original` (config.txt as it was before we added the block)
 * is given and the file hasn't been changed by anyone else since, it is restored byte for byte.
 */
export function removeBlock(configText, original) {
  if (original != null && addBlock(original) === configText) return original;
  if (!hasBlock(configText)) return configText;
  const re = new RegExp(`(\\r?\\n)?${escape(BLOCK_START)}[\\s\\S]*?${escape(BLOCK_END)}(\\r?\\n)?`);
  return configText.replace(re, (m, before, after) => (before && after ? before : ''));
}
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Look for other APO config (e.g. a Peace preset) that would ALSO apply to the Scape:
 * any gain or filter line while the device scope is "all" (or not set).
 * `files` = { 'config.txt': text, 'peace.txt': text, ... } as available.
 */
export function findConflicts(files) {
  const issues = [];
  const visit = (name, depth = 0) => {
    const text = files[name];
    if (text == null || depth > 4 || name === BOOST_FILE) return;
    let scopeAll = true;
    for (const raw of text.split(/\r?\n/)) {
      const line = raw.trim();
      if (!line || line.startsWith('#')) continue;
      const m = /^([A-Za-z]+(?:\s*\d+)?)\s*:\s*(.*)$/.exec(line);
      if (!m) continue;
      const [, cmd, arg] = m;
      const c = cmd.toLowerCase();
      if (c === 'device') scopeAll = /^all$/i.test(arg.trim());
      else if (c === 'include') arg.split(';').map((s) => s.trim()).forEach((f) => visit(f, depth + 1));
      else if (scopeAll && c === 'preamp' && Math.abs(parseFloat(arg)) > 0.01) issues.push(`${name}: “${line}” applies to all devices`);
      else if (scopeAll && /^(filter\s*\d*|graphiceq|convolution)$/i.test(cmd) && !/\bOFF\b/.test(arg)) issues.push(`${name}: “${line.slice(0, 60)}” applies to all devices`);
    }
  };
  visit('config.txt');
  // keep the list short: preamp lines + a count of filters
  const filters = issues.filter((i) => !/Preamp/.test(i));
  return [...issues.filter((i) => /Preamp/.test(i)), ...(filters.length ? [`${filters.length} filter line(s) apply to all devices`] : [])];
}
